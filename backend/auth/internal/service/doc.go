// Package service реализует passwordless-аутентификацию по email-коду и управление JWT-сессиями.
//
// Использование:
//
//	svc := service.New(cfg, codeStore, userClient, mailSender)
//
// Конфигурация:
//
//	AUTH_CODE_TTL   — время жизни одноразового кода.
//	AUTH_JWT_SECRET — HMAC-секрет JWT.
//	SMTP_*          — настройки отправки email.
//
// Ограничения:
//
//   - Конструктор не выполняет I/O.
//   - Для одного email может быть активно несколько кодов до истечения TTL.
//   - Успешный вход по любому коду удаляет все активные коды этого email и сбрасывает cooldown.
//   - Повторная отправка кода ограничена cooldown-окном с нарастающей задержкой.
//   - Logout everywhere опирается на индекс токенов пользователя и явно отзывает текущий токен.
//   - JWT не имеет срока действия и должен отзываться через logout.
