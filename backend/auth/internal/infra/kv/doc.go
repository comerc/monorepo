// Package kv реализует хранение email-кодов, cooldown-окон и отозванных JWT в Redis.
//
// Использование:
//
//	store := kv.New(redisClient)
//
// Конфигурация:
//
//	REDIS_* — параметры подключения задаются в internal/config.
//
// Ограничения:
//
//   - Конструктор не выполняет I/O.
//   - Индекс активных кодов email имеет TTL и очищается вместе с кодами.
//   - Индекс токенов пользователя нужен для logout everywhere.
//   - Отозванные JWT хранятся без TTL, потому что токены не имеют срока действия.
package kv
